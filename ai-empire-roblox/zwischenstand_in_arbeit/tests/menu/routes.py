#!/usr/bin/env python3
"""T11 helper (menu package): grep every (app, section) pair the game can open the Computer / Menu with.

Scans work/src for the literal forms the code uses (Computer.open/show, nav.show, prompt/screen opts `app = ...,
section = ...`, OWNER_COMPUTER payloads, phone rings `open = ..., section = ...`, GoalText `view.app/view.section`,
AssistantService advice tuples `"app", "section"`) and writes tests/menu/.routes_found.luau:
    return { { app = "empire", section = "clients", where = "File:123" }, ... }
test_client.luau checks that each pair lands on an existing Menu page (route table B9).
Usage: python3 tests/menu/routes.py [src_dir] [out_file]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "work", "src")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "tests", "menu", ".routes_found.luau")

APPS = "empire|lab|data|compute|market|studio|arena|campus|shop|home|clients|team"
PATTERNS = [
    re.compile(r'Computer\.(?:open|show)\(\s*"(\w+)"\s*(?:,\s*"(\w+)")?'),
    re.compile(r'\b(?:nav|navigation|navigator)\.show\(\s*"(\w+)"\s*(?:,\s*"(\w+)")?'),
    re.compile(r'\bapp\s*=\s*"(\w+)"(?:[^\n]*?\bsection\s*=\s*"(\w+)")?'),
    re.compile(r'\bopen\s*=\s*"(' + APPS + r')"(?:[^\n]*?\bsection\s*=\s*"(\w+)")?'),
    re.compile(r'SetAttribute\(\s*"App"\s*,\s*"(\w+)"\s*\)'),
    re.compile(r'"(' + APPS + r')"\s*,\s*"(\w+)"\s*(?:end\b|\)|$)'),
    re.compile(r'"(' + APPS + r')"\s*,\s*nil\b'),
    re.compile(r'"(' + APPS + r')"\s*,\s*if [^\n]*?then\s*"(\w+)"'),
]
VIEW_APP = re.compile(r'view\.app\s*=\s*"(\w+)"')
VIEW_SECTION = re.compile(r'view\.section\s*=\s*(?:if [^\n]*?then\s*)?"(\w+)"')

found = []
seen = set()


def add(app, section, where):
    key = (app, section or "")
    if key in seen:
        return
    seen.add(key)
    found.append((app, section, where))


for dirpath, _, files in os.walk(SRC):
    for name in sorted(files):
        if not name.endswith(".luau"):
            continue
        path = os.path.join(dirpath, name)
        rel = os.path.relpath(path, SRC)
        short = name.replace(".module.luau", "").replace(".luau", "")
        with open(path, encoding="utf-8") as f:
            lines = f.read().split("\n")
        last_view_app = None
        for i, line in enumerate(lines, 1):
            code = line.split("--", 1)[0] if not line.lstrip().startswith("--") else ""
            if not code.strip():
                continue
            for pat in PATTERNS:
                for m in pat.finditer(code):
                    app = m.group(1)
                    section = m.group(2) if m.lastindex and m.lastindex >= 2 else None
                    add(app, section, f"{short}:{i}")
            m = VIEW_APP.search(code)
            if m:
                last_view_app = m.group(1)
                add(last_view_app, None, f"{short}:{i}")
            m = VIEW_SECTION.search(code)
            if m and last_view_app:
                add(last_view_app, m.group(1), f"{short}:{i}")

with open(OUT, "w", encoding="utf-8") as f:
    f.write("-- generated by tests/menu/routes.py (do not edit)\nreturn {\n")
    for app, section, where in found:
        sec = f'"{section}"' if section else "nil"
        f.write(f'\t{{ app = "{app}", section = {sec}, where = "{where}" }},\n')
    f.write("}\n")
print(f"routes.py: {len(found)} distinct (app, section) pairs -> {os.path.relpath(OUT, ROOT)}")
