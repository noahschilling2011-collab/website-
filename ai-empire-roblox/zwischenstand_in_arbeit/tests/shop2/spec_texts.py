#!/usr/bin/env python3
"""T21 data: the SHOP_SPEC section 2 catalogue table -> tests/shop2/.spec_texts.luau (key -> name, tag, tab, text),
read by test_math.luau, which compares every ShopConfig string with it. Also lists every string literal of the shop
UI/config files for the forbidden-word check. usage: spec_texts.py <SHOP_SPEC.md> <src root> <out.luau>"""
import re, sys, json
spec, src, out = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(spec, encoding="utf-8").read()
sec = text.split("## 2. Catalogue", 1)[1].split("\n## 3.", 1)[0]
items = {}
TABS = {"Speed-ups": "speedups", "Boosts": "boosts", "Style": "style", "Extras": "extras"}
for line in sec.splitlines():
    if not line.startswith("| ") or line.startswith("| key") or line.startswith("|---"):
        continue
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    if len(cells) < 6:
        continue
    key = cells[0].strip("*")
    m = re.match(r'^"(.*?)"', cells[5])
    if not m:
        m2 = None
    items[key] = {"name": cells[2], "tag": cells[3], "tab": TABS.get(cells[4], cells[4]), "text": m.group(1) if m else cells[5]}
FILES = [
    "ReplicatedStorage/Shared/Config/ShopConfig.module.luau",
    "ReplicatedStorage/Shared/ShopMath.module.luau",
    "StarterPlayer/StarterPlayerScripts/Client/UI/Shop/ShopCore.module.luau",
    "StarterPlayer/StarterPlayerScripts/Client/UI/Shop/UseSheet.module.luau",
    "StarterPlayer/StarterPlayerScripts/Client/UI/Apps/ShopApp.module.luau",
]
strings = []
for f in FILES:
    body = open(f"{src}/{f}", encoding="utf-8").read()
    body = re.sub(r"--\[\[.*?\]\]", "", body, flags=re.S)
    for ln in body.splitlines():
        code = ln.split("--", 1)[0] if not re.search(r'["`][^"`]*--[^"`]*["`]', ln) else ln
        for s in re.findall(r'"((?:[^"\\]|\\.)*)"|`((?:[^`\\]|\\.)*)`', code):
            v = s[0] or s[1]
            if len(v) >= 3 and " " in v:
                strings.append([f.rsplit("/", 1)[1], v])
def lua(v):
    return json.dumps(v, ensure_ascii=False)
with open(out, "w", encoding="utf-8") as o:
    o.write("-- generated by spec_texts.py from design/SHOP_SPEC.md section 2 (do not edit)\nreturn {\n\titems = {\n")
    for k, v in items.items():
        o.write(f"\t\t[{lua(k)}] = {{ name = {lua(v['name'])}, tag = {lua(v['tag'])}, tab = {lua(v['tab'])}, text = {lua(v['text'])} }},\n")
    o.write("\t},\n\tstrings = {\n")
    for f, v in strings:
        o.write(f"\t\t{{ {lua(f)}, {lua(v)} }},\n")
    o.write("\t},\n}\n")
print(f"spec_texts: {len(items)} catalogue rows, {len(strings)} strings")
