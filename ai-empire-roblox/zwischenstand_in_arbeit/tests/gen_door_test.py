#!/usr/bin/env python3
"""Bundle the modules DoorService needs + tests/door_service_test_body.luau into
tests/door_service_test.luau and run it with the headless Roblox mock (harness/mock.luau).

usage: python3 tests/gen_door_test.py && tools/luau tests/door_service_test.luau
(The harness manifest/sources files are not touched; this test builds its own small tree.)
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "work", "src")
MODULES = [
    ("ReplicatedStorage/Shared/Config/BuildingPlan.module.luau", ["ReplicatedStorage", "Shared", "Config", "BuildingPlan"]),
    ("ReplicatedStorage/Shared/Config/ArchPalette.module.luau", ["ReplicatedStorage", "Shared", "Config", "ArchPalette"]),
    ("ReplicatedStorage/Shared/Config/CampusAudioConfig.module.luau", ["ReplicatedStorage", "Shared", "Config", "CampusAudioConfig"]),
    ("ReplicatedStorage/Shared/BuildingLayout.module.luau", ["ReplicatedStorage", "Shared", "BuildingLayout"]),
    ("ServerScriptService/Server/Services/CampusSoundService.module.luau", ["ServerScriptService", "Server", "Services", "CampusSoundService"]),
    ("ServerScriptService/Server/Services/DoorService.module.luau", ["ServerScriptService", "Server", "Services", "DoorService"]),
]


def lstr(s):
    lvl = 0
    while ("]" + "=" * lvl + "]") in s or s.endswith("]" + "=" * lvl):
        lvl += 1
    eq = "=" * lvl
    return "[" + eq + "[\n" + s + "]" + eq + "]"


def main():
    out = ["--!nocheck", "-- GENERATED by tests/gen_door_test.py — edit door_service_test_body.luau instead.",
           'local M = require("../harness/mock")', "local MANIFEST = {"]
    folders = set()
    for _, path in MODULES:
        for i in range(2, len(path)):
            folders.add(tuple(path[:i]))
    for f in sorted(folders, key=len):
        out.append("{path={" + ",".join(json.dumps(x) for x in f) + "},class=\"Folder\"},")
    for rel, path in MODULES:
        out.append("{path={" + ",".join(json.dumps(x) for x in path) + "},class=\"ModuleScript\",file=" + json.dumps(rel) + "},")
    out.append("}")
    out.append("local SOURCES = {}")
    for rel, _ in MODULES:
        with open(os.path.join(SRC, rel), encoding="utf-8") as fh:
            out.append("SOURCES[" + json.dumps(rel) + "]=" + lstr(fh.read()))
    out.append("M.loadTree(MANIFEST, SOURCES)")
    with open(os.path.join(ROOT, "tests", "door_service_test_body.luau"), encoding="utf-8") as fh:
        out.append(fh.read())
    with open(os.path.join(ROOT, "tests", "door_service_test.luau"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("tests/door_service_test.luau written")


if __name__ == "__main__":
    main()
