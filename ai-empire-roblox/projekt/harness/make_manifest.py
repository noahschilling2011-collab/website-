#!/usr/bin/env python3
"""Scan work/src and generate harness/manifest.luau + harness/sources.luau.

manifest.luau returns an array of {path={seg,...}, class="ModuleScript"|"Script"|"LocalScript"|"Folder", file="rel/path"|nil}
sources.luau  returns {[relpath]=source} using long brackets whose level never occurs in the text.
Run before every harness run (run.sh does it) so modules added by other agents are picked up.
"""
import os, sys, json

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.environ.get("HARNESS_SRC", os.path.join(ROOT, "work", "src"))
GEN = HERE
# optional: make_manifest.py --src DIR --gen DIR  (gen dir must be inside harness/ so luau can require it)
if "--src" in sys.argv:
    SRC = os.path.abspath(sys.argv[sys.argv.index("--src") + 1])
if "--gen" in sys.argv:
    GEN = os.path.abspath(sys.argv[sys.argv.index("--gen") + 1])
    os.makedirs(GEN, exist_ok=True)

SUFFIX = {".module.luau": "ModuleScript", ".server.luau": "Script", ".client.luau": "LocalScript",
          ".module.lua": "ModuleScript", ".server.lua": "Script", ".client.lua": "LocalScript"}


def lstr(s):
    """Luau long-bracket literal for s (exact round trip)."""
    lvl = 0
    while ("]" + "=" * lvl + "]") in s or s.endswith("]" + "=" * lvl):
        lvl += 1
    eq = "=" * lvl
    # a newline right after the opening bracket is skipped by the lexer -> add one so a
    # leading newline in s survives
    return "[" + eq + "[\n" + s + "]" + eq + "]"


def luaq(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    entries = []   # (segments, class, relfile)
    scripts = set()
    dirs = set()
    for dirpath, dirnames, filenames in os.walk(SRC):
        dirnames.sort()
        rel = os.path.relpath(dirpath, SRC)
        segs = [] if rel == "." else rel.split(os.sep)
        if segs:
            dirs.add(tuple(segs))
        for fn in sorted(filenames):
            for suf, cls in SUFFIX.items():
                if fn.endswith(suf):
                    name = fn[: -len(suf)]
                    path = tuple(segs + [name])
                    relfile = os.path.relpath(os.path.join(dirpath, fn), SRC).replace(os.sep, "/")
                    entries.append((path, cls, relfile))
                    scripts.add(path)
                    break
    # directories that are not also scripts are Folders (top level = services, created by the mock)
    for d in sorted(dirs):
        if d not in scripts and len(d) > 1:
            entries.append((d, "Folder", None))
    entries.sort(key=lambda e: (len(e[0]), e[0]))
    man = ["-- GENERATED by harness/make_manifest.py from " + SRC, "return {"]
    for path, cls, relfile in entries:
        segs = ",".join(luaq(s) for s in path)
        f = (",file=" + luaq(relfile)) if relfile else ""
        man.append("{path={" + segs + "},class=" + luaq(cls) + f + "},")
    man.append("}")
    with open(os.path.join(GEN, "manifest.luau"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(man) + "\n")
    src = ["-- GENERATED by harness/make_manifest.py (file contents of " + SRC + ")", "local S={}"]
    n = 0
    for path, cls, relfile in entries:
        if not relfile:
            continue
        with open(os.path.join(SRC, relfile), encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        src.append("S[" + luaq(relfile) + "]=" + lstr(text))
        n += 1
    src.append("return S")
    with open(os.path.join(GEN, "sources.luau"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(src) + "\n")
    print(f"manifest: {len(entries)} entries, {n} scripts from {SRC}", file=sys.stderr)


if __name__ == "__main__":
    main()
